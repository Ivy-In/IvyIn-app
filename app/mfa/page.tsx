"use client";

import { AuthBrand } from "@/components/AuthBrand";
import { useEffect, useState } from "react";
import { createClient } from "@/lib/supabase/browser";

// Staff second factor (TOTP). Shows a QR code the first time, then asks for a code on each sign-in.
export default function MfaPage() {
  const [status, setStatus] = useState("Checking your account…");
  const [qr, setQr] = useState<string | null>(null);
  const [secret, setSecret] = useState<string | null>(null);
  const [factorId, setFactorId] = useState<string | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    const supabase = createClient();
    (async () => {
      const { data: aal } = await supabase.auth.mfa.getAuthenticatorAssuranceLevel();
      if (aal?.currentLevel === "aal2") {
        window.location.href = "/portal";
        return;
      }

      const { data: factors, error: listErr } = await supabase.auth.mfa.listFactors();
      if (listErr) {
        setError("Could not load your security settings. Log in again.");
        return;
      }

      const verified = factors?.totp.find((f) => f.status === "verified");
      if (verified) {
        setFactorId(verified.id);
        setStatus("Enter the 6-digit code from your authenticator app.");
        return;
      }

      // No verified factor yet. Remove any half-finished enrolment, then start again.
      for (const f of factors?.totp ?? []) {
        await supabase.auth.mfa.unenroll({ factorId: f.id });
      }

      const { data, error: enrollErr } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "IvyIn staff",
      });
      if (enrollErr || !data) {
        setError(enrollErr?.message ?? "Could not start setup.");
        return;
      }
      setFactorId(data.id);
      setQr(data.totp.qr_code);
      setSecret(data.totp.secret);
      setStatus("Scan this code with your authenticator app, then enter the 6-digit code it shows.");
    })();
  }, []);

  async function verify(e: React.FormEvent) {
    e.preventDefault();
    if (!factorId) return;
    setBusy(true);
    setError(null);
    const supabase = createClient();
    const { error: verifyErr } = await supabase.auth.mfa.challengeAndVerify({
      factorId,
      code: code.trim(),
    });
    setBusy(false);
    if (verifyErr) {
      setError("That code didn't work. Check the time on your phone and try again.");
      return;
    }
    window.location.href = "/portal";
  }

  return (
    <main className="wrap" style={{ maxWidth: 460 }}>
      <AuthBrand />
      <div className="card">
        <h1>Two-step verification</h1>
        <p>{status}</p>
        {qr && (
          // The QR code is an SVG data URL generated by Supabase for this factor only.
          // eslint-disable-next-line @next/next/no-img-element
          <img src={qr} alt="Authenticator setup QR code" width={200} height={200} />
        )}
        {secret && (
          <p className="muted">
            Can't scan? Enter this key manually: <code>{secret}</code>
          </p>
        )}
        {factorId && (
          <form onSubmit={verify}>
            <label htmlFor="code">6-digit code</label>
            <input
              id="code"
              inputMode="numeric"
              autoComplete="one-time-code"
              pattern="[0-9]{6}"
              maxLength={6}
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/\D/g, ""))}
              required
            />
            <p style={{ marginTop: 18 }}>
              <button className="btn" type="submit" disabled={busy || code.length !== 6}>
                {busy ? "Checking…" : "Verify"}
              </button>
            </p>
          </form>
        )}
        {error && <p className="error" role="alert">{error}</p>}
      </div>
    </main>
  );
}
